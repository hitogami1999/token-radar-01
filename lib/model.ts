// Token Radar, model "radar-2": one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol in the snapshot that records no token and is not a wrapped,
// staked or bridged product of a token that already trades. The snapshot's watchlist (40 protocols
// at or above the $50M floor) is the floor, never the ceiling: the board also carries the 163
// further pre-token protocols the house rule leaves out, including the ones below the floor and
// the ones above it that DefiLlama ties to a parent protocol. Live-token protocols are never
// ranked; they are kept apart and shown with the market cap the market itself gives them.
//
// Implied value is derived from the snapshot's own figures only, never from a list of names:
//
//   compMultiple(category)  the median market-cap-to-TVL ratio of the snapshot's live-token
//                           protocols in the same category (at least 3 of them, else the median
//                           over every live protocol), clamped to [0.08, 0.80] so one thin
//                           category cannot mint an absurd multiple
//   base                  = tvl_usd x compMultiple(category)
//   growthMult            = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   breadthMult           = 1 + min(chains - 1, 4) x 0.03   (more chains, wider distribution)
//   maturityMult          = 0.65 + min(age_days, 1095) / 1095 x 0.35
//                           (age_days unknown: 365; older, longer-running protocols have
//                           survived longer with no token, so a launch is worth more)
//   implied               = max(1, round(base x growthMult x breadthMult x maturityMult))
//
// A farm plan is derived the same way, from the protocol's own record: its category picks the
// action, its first chain picks the gas cost, its TVL picks the capital, its age picks the hold.
// Every step states what it costs and how long it takes.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

